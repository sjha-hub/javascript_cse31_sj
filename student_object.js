// Using curly braces {} - Most common way
let student = {
  name: "John",
  age: 30,
  cgpa:9.8,
  isPass:true
  
};

// Dot notation (preferred)
console.log(student);  // all info

// Bracket notation (useful for dynamic keys)
console.log(student["age"]);  // 30

console.log(student.name);
student.name="John kumar ";
console.log(student);

